<?php

namespace App\Controllers\Admin;

use Psr\Http\Message\ResponseInterface as Response;
use Psr\Http\Message\ServerRequestInterface as Request;
use Exception;
use App\Helpers\General;
use App\Helpers\ApiResponse;
use App\Services\Admin\AdminArticleAgentService;
use App\Validators\Admin\AdminArticleAgentValidator;

class AdminArticleAgentController
{
  public function __construct(
    private General $helper,
    private AdminArticleAgentService $service,
    private AdminArticleAgentValidator $validator,
    private ApiResponse $apiResponse
  ) {}

  public function step1_inputTopic(Request $request, Response $response)
  {
    try {
      //* INPUT
      $input = (array) $request->getParsedBody();

      //* VALIDATOR
      $this->validator->validate('step1_inputTopic', $input);

      //* SERVICE
      $data = $this->service->step1_inputTopic($input);

      return $this->apiResponse->success($response, $data);
    }
    catch (Exception $e) {
      return $this->apiResponse->handleException($response, $e);
    }
  }

